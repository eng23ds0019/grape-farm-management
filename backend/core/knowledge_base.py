def search_knowledge(query: str) -> str:
    """
    Enhanced multi-section knowledge retrieval engine.
    Cleans prompt tags and ranks relevant agronomic sections.
    """
    import re
    # Strip instruction tags if present
    clean = re.sub(r"\[Language:.*?User question\]:\s*", "", query, flags=re.IGNORECASE).strip()
    if not clean:
        clean = query

    query_lower = clean.lower()
    sections = GRAPE_KNOWLEDGE_BASE.split("═══════════════════════════════════════════════════════════════════════════")

    scored_sections = []
    keywords = [w for w in re.findall(r'\w+', query_lower) if len(w) > 2]

    for section in sections:
        if len(section.strip()) < 50:
            continue
        sec_lower = section.lower()
        score = 0
        for kw in keywords:
            if kw in sec_lower:
                score += sec_lower.count(kw)
        
        if score > 0:
            scored_sections.append((score, section.strip()))

    if scored_sections:
        # Sort by score descending and return top matching sections
        scored_sections.sort(key=lambda x: x[0], reverse=True)
        top_text = "\n\n---\n\n".join([sec[1] for sec in scored_sections[:3]])
        return top_text

    # Fallback: Return complete knowledge base if generic or short query
    return GRAPE_KNOWLEDGE_BASE
